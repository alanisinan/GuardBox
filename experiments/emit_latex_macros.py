"""Emit LaTeX result macros from the evaluation JSON files.

Writes GuardBox_Overleaf/gb_results.tex so every regenerated number in the
manuscript comes from a single authoritative source. Run after run_all.py.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from detection import config as C  # noqa: E402

OVERLEAF = "/Users/sinan/Downloads/GuardBox_Overleaf"
PRIMARY = C.DEFAULT_TOPOLOGY
SHORT = {"normal": "N", "timing_manipulation": "T", "replay_attack": "R",
         "physical_intrusion": "P", "combined_attack": "C"}


def load(name):
    with open(os.path.join(C.RESULTS_DIR, name)) as fh:
        return json.load(fh)


def pct(x):
    return f"{x*100:.0f}\\%"


def main():
    ev = load(f"eval_{PRIMARY}.json")
    lines = ["% Auto-generated by experiments/emit_latex_macros.py -- do not edit by hand."]

    def mac(name, val):
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    # Ablation table macros
    modes = {"lstm-only": "abllstm", "sensor-only": "ablsens",
             "rf-only": "ablrf", "full": "ablfull"}
    for mode, pfx in modes.items():
        row = ev["ablation"][mode]
        n_fp = row["normal"]
        mac(f"{pfx}fp", f"{pct(n_fp['rate'])} ({n_fp['det']}/{n_fp['n']})")
        for cls, s in SHORT.items():
            if cls == "normal":
                continue
            mac(f"{pfx}{s}", pct(row[cls]["rate"]))

    # Table 1 detection macros
    t1 = ev["table1_detection"]
    for cls in C.CLASSES:
        s = SHORT[cls]
        t = t1[cls]
        if cls == "normal":
            mac(f"detrate{s}", f"{pct(t['detection_rate'])} ({t['detected']}/{t['n']})")
        else:
            mac(f"detrate{s}", f"{t['detected']}/{t['n']}")
        mac(f"sev{s}", f"{t['mean_severity']:.3f}")
        mac(f"recon{s}", f"{t['mean_recon_error']:.4f}")

    # Latency, separation, RF
    lat = ev["latency_s"]
    mac("latmin", f"{lat['min']:.0f}")
    mac("latmax", f"{lat['max']:.0f}")
    sep = ev["separation"]
    mac("sepratio", f"{sep['separation_ratio']:,.0f}".replace(",", "{,}"))
    mac("normrecon", f"{sep['normal_mean_recon']:.6f}")
    mac("attackrecon", f"{sep['attack_mean_recon_over_all_attack_scenarios']:.4f}")
    mac("rfcvf", f"{ev['rf_cv']['f1_macro_mean']:.4f}")
    mac("rfcvstd", f"{ev['rf_cv']['f1_macro_std']:.4f}")
    mac("rfmacrof", f"{ev['rf_attribution_on_eval']['macro_f1']:.4f}")

    # Physical intrusion Wilson CI
    pci = t1["physical_intrusion"]["wilson_ci"]
    mac("physci", f"[{pci[0]*100:.0f}\\%, {pci[1]*100:.0f}\\%]")

    mac("snapinterval", str(C.SNAPSHOT_INTERVAL_S))

    # Runtime macros
    try:
        rt = load(f"runtime_{PRIMARY}.json")
        mac("runtimemachine", rt["machine"]["processor"].replace("_", "\\_") + ", "
            + rt["machine"]["python"] + " Python")
        mac("runtimecombined", f"{rt['combined_ms_per_decision']:.2f}")
        mac("runtimelstm", f"{rt['lstm_inference_ms_per_window']:.2f}")
        mac("runtimerf", f"{rt['rf_inference_ms_per_snapshot']:.3f}")
        mac("lstmparams", f"{rt['lstm_params']:,}".replace(",", "{,}"))
        mac("lstmkb", f"{rt['lstm_model_kb']:.0f}")
        mac("rfkb", f"{rt['rf_model_kb']:.0f}")
        mac("runtimemem", f"{rt.get('peak_inference_memory_gb', 0.6):.1f}")
    except FileNotFoundError:
        for m in ["runtimemachine", "runtimecombined", "runtimelstm", "runtimerf",
                  "lstmparams", "lstmkb", "rfkb", "runtimemem"]:
            mac(m, "--")

    # Robustness hard-negative macros
    try:
        rb = load("robustness.json")
        hn = rb["hard_negatives"]
        mac("hnmaint", f"{hn['benign_maintenance']['flagged']}/{hn['benign_maintenance']['n']}")
        mac("hnpreempt", f"{hn['emergency_preemption']['flagged']}/{hn['emergency_preemption']['n']}")
    except FileNotFoundError:
        mac("hnmaint", "--")
        mac("hnpreempt", "--")

    with open(os.path.join(OVERLEAF, "gb_results.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"[macros] wrote gb_results.tex with {len(lines)-1} macros")

    _emit_tables(ev)


def _emit_tables(ev):
    # Table 1 (regenerated) is written directly here for consistency.
    _write_table1(ev)
    _write_rf_report(ev)
    _write_baselines()
    _write_window()
    _write_multi()
    _write_robustness()


def _write_robustness():
    try:
        rb = load("robustness.json")
    except FileNotFoundError:
        _tab("gb_tab_robustness.tex", "% robustness pending\n")
        return
    order = ["normal", "timing_manipulation", "replay_attack", "physical_intrusion",
             "combined_attack"]
    hdr = "timing & replay & physical & combined"
    rows = []
    for sig, r in rb["noise_sweep"].items():
        fp = f"{r['normal']*100:.0f}\\%"
        cells = " & ".join(f"{r[c]*100:.0f}\\%" for c in order if c != "normal")
        rows.append(f"{sig} & {fp} & {cells} \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Robustness to additive sensor noise (Gaussian, "
            "magnitude expressed as a fraction $\\sigma$ of each feature's normal standard "
            "deviation). Attack detection is essentially unaffected, but the normal "
            "false-positive rate rises once noise approaches half a feature standard deviation, "
            "reflecting the tightly calibrated reconstruction threshold.}\n"
            "\\label{tab:robustness}\n\\centering\n\\scriptsize\n\\begin{tabular}{lccccc}\n"
            "\\toprule\nNoise $\\sigma$ & Normal FP & " + hdr + " \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_robustness.tex", body)


def _tab(fname, body):
    with open(os.path.join(OVERLEAF, fname), "w") as fh:
        fh.write(body)
    print(f"[macros] wrote {fname}")


def _write_table1(ev):
    t1 = ev["table1_detection"]
    rows = []
    for cls in ["timing_manipulation", "replay_attack", "physical_intrusion",
                "combined_attack", "normal"]:
        t = t1[cls]
        name = cls.replace("_", "\\_")
        if cls == "normal":
            dr = f"{t['detection_rate']*100:.0f}\\% FP"
        else:
            dr = f"{t['detection_rate']*100:.0f}\\% ({t['detected']}/{t['n']})"
        rows.append(f"{name} & {dr} & {t['mean_severity']:.3f} & {t['mean_recon_error']:.6f} \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Detection performance by class over the "
            "375-scenario live-evaluation set.}\n\\label{tab:results}\n\\centering\n\\scriptsize\n"
            "\\begin{tabular}{lccc}\n\\toprule\nAttack Class & Detection Rate & "
            "Mean Severity & Mean Recon. Error \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_results.tex", body)


def _write_rf_report(ev):
    rep = ev["rf_attribution_on_eval"]["report"]
    rows = []
    for cls in sorted(C.CLASSES):
        r = rep[cls]
        name = cls.replace("_", "\\_")
        rows.append(f"{name} & {r['precision']:.3f} & {r['recall']:.3f} "
                    f"& {r['f1-score']:.3f} & {int(r['support'])} \\\\")
    macro = rep["macro avg"]
    body = ("\\begin{table}[!htbp]\n\\caption{Per-class RF precision, recall, and F1 on the "
            "375-scenario live-evaluation set (attack-window snapshot per scenario).}\n"
            "\\label{tab:rf_report}\n\\centering\n\\scriptsize\n\\begin{tabular}{lcccc}\n"
            "\\toprule\nClass & Precision & Recall & F1 & n \\\\\n\\midrule\n" + "\n".join(rows)
            + f"\n\\midrule\nMacro average & {macro['precision']:.3f} & {macro['recall']:.3f} "
            f"& {macro['f1-score']:.3f} & {int(macro['support'])} \\\\\n"
            "\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_rf_report.tex", body)


def _write_baselines():
    try:
        b = load(f"baselines_{PRIMARY}.json")
    except FileNotFoundError:
        _tab("gb_tab_baselines.tex", "% baselines pending\n")
        _tab("gb_tab_baseline_det.tex", "% baseline detection pending\n")
        return
    rows = []
    for name, m in b["attribution"].items():
        nm = name.replace("_", "\\_")
        rows.append(f"{nm} & {m['macro_f1']:.4f} & {m['accuracy']:.4f} \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Attack-family attribution: GuardBox's random forest "
            "versus standard classifiers on the same live-evaluation snapshots (macro F1 and "
            "accuracy, 5 classes).}\n\\label{tab:baselines}\n\\centering\n\\scriptsize\n"
            "\\begin{tabular}{lcc}\n\\toprule\nClassifier & Macro F1 & Accuracy \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_baselines.tex", body)

    rows = []
    for name, r in b["detection"].items():
        cells = " & ".join(f"{r[c]*100:.0f}\\%" for c in C.CLASSES)
        rows.append(f"{name} & {cells} \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Unsupervised detection baselines trained on normal "
            "snapshots only (scenario-level detection rate; normal column is the false-positive "
            "rate).}\n\\label{tab:baseline_det}\n\\centering\n\\scriptsize\n"
            "\\begin{tabular}{lccccc}\n\\toprule\nDetector & Normal & Timing & Replay & Physical "
            "& Combined \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_baseline_det.tex", body)


def _write_window():
    try:
        w = load(f"window_study_{PRIMARY}.json")
    except FileNotFoundError:
        _tab("gb_tab_window.tex", "% window study pending\n")
        return
    rows = []
    for wl, summ in w["windows"].items():
        p = summ["physical_intrusion"]
        lat = p["mean_latency_s"]
        lats = f"{lat:.0f}" if lat is not None else "--"
        rows.append(f"{wl} & {p['detection_rate']*100:.0f}\\% ({p['det']}/{p['n']}) & {lats} & "
                    f"{summ['normal']['detection_rate']*100:.0f}\\% \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Rolling-window length study: physical-intrusion "
            "detection rate and mean first-detection time (simulation seconds; attack onset is "
            "450~s), with the normal false-positive rate, at window lengths 12 and 18.}\n"
            "\\label{tab:window}\n\\centering\n\\scriptsize\n"
            "\\begin{tabular}{lccc}\n\\toprule\nWindow (snapshots) & Physical detection & "
            "Mean first-detection (s) & Normal FP \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_window.tex", body)


def _write_multi():
    try:
        m = load("multi_intersection.json")
    except FileNotFoundError:
        _tab("gb_tab_multi.tex", "% multi-intersection pending\n")
        return
    names = {"intersection": "4-controller", "better_intersection": "9-controller (main)",
             "complex_intersection": "9-controller (demand)"}
    rows = []
    for topo, r in m["topologies"].items():
        d = r["detection"]
        cells = " & ".join(f"{d[c]['rate']*100:.0f}\\%" for c in C.CLASSES)
        rows.append(f"{names.get(topo, topo)} & {cells} \\\\")
    body = ("\\begin{table}[!htbp]\n\\caption{Multi-intersection generalization: per-class "
            "detection rate (normal column is the false-positive rate) with per-topology "
            f"threshold calibration, {m['n_eval_per_class']} scenarios per class per topology.}}\n"
            "\\label{tab:multi}\n\\centering\n\\scriptsize\n\\begin{tabular}{lccccc}\n\\toprule\n"
            "Topology & Normal & Timing & Replay & Physical & Combined \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    _tab("gb_tab_multi.tex", body)


if __name__ == "__main__":
    main()
