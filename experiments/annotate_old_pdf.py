LEGEND = ("REVISION MARK-UP KEY  |  YELLOW = text modified/updated   "
          "PINK = removed or replaced   GREEN = content added nearby.  "
          "Click a highlight to read the note: what changed and which reviewer/editor "
          "point it addresses. Prepared from the revised manuscript.")


def main():
    doc = fitz.open(SRC)
    misses = []
    placed = 0
    for page_idx, anchor, kind, note in ANN:
        color = COLORS[kind]
        rects = []
        page = doc[page_idx]
        hits = page.search_for(anchor)
        if not hits:
            # fall back to a global search
            for p in range(doc.page_count):
                h = doc[p].search_for(anchor)
                if h:
                    page = doc[p]
                    hits = h
                    break
        if not hits:
            misses.append((page_idx, anchor))
            continue
        # annotate the first hit (and same-line continuation rects)
        target = hits[:2] if len(hits) > 1 and kind != "modified" else hits[:1]
        for r in target:
            annot = page.add_highlight_annot(r)
            annot.set_colors(stroke=color)
            annot.set_info(title="Revision", content=f"[{kind.upper()}] {note}")
            annot.set_opacity(0.45)
            annot.update()
        placed += 1

    # Legend as a sticky note on page 1, top-left margin.
    p0 = doc[0]
    ln = p0.add_text_annot(fitz.Point(36, 30), LEGEND, icon="Note")
    ln.set_colors(stroke=(0.1, 0.3, 0.8))
    ln.set_info(title="How to read this mark-up", content=LEGEND)
    ln.update()

    doc.save(OUT, garbage=4, deflate=True)
    print(f"placed {placed}/{len(ANN)} annotations -> {OUT}")
    if misses:
        print("MISSED anchors (fix these):")
        for pi, a in misses:
            print(f"  p{pi}: {a!r}")


if __name__ == "__main__":
    main()
